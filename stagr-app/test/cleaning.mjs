// Browser check for the cleaning-friendly additions: checklist templates, "every 2 weeks", entry notes on the visit. Run: node test/cleaning.mjs
import { execSync } from 'node:child_process';
import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
const PGBIN = '/usr/lib/postgresql/16/bin', DB = 'stagr_clean';
const psql = c => execSync(`${PGBIN}/psql -h /tmp -p 5544 -U postgres -qAt -c "${c}"`);
psql(`DROP DATABASE IF EXISTS ${DB}`); psql(`CREATE DATABASE ${DB}`);
process.env.DATABASE_URL = `postgresql://postgres@/${DB}?host=/tmp&port=5544`; process.env.QUIET_HOURS = 'off'; process.env.SESSION_SECRET = 'clean-secret-clean-secret-clean-secret';
const { start } = await import('../dev/server.mjs'); const srv = await start(8797); const BASE = 'http://localhost:8797';
let pass = 0, fail = 0; const ok = (n, c, x) => { if (c) { pass++; console.log('PASS', n); } else { fail++; console.log('FAIL', n, x ?? ''); } };
const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1200, height: 900 } }); const page = await ctx.newPage();
const errs = []; page.on('pageerror', e => errs.push(String(e.stack || e).slice(0, 400)));
const api = async (m, u, body) => page.evaluate(async ([m, u, body]) => { const r = await fetch('/api' + u, { method: m, headers: { 'content-type': 'application/json' }, body: body ? JSON.stringify(body) : undefined }); return r.json(); }, [m, u, body]);
await page.goto(BASE + '/app');
const su = await api('POST', '/auth/signup', { business: 'Sparkle Co', name: 'Sam', email: 'sam@example.com', password: 'longpassword1', trade: 'cleaning' });
ok('signed up as cleaning', !!su.user, su);
const c = await api('POST', '/customers', { name: 'Pat Home', phone: '5551230000', property: { address: '12 Oak St', city: 'Austin', state: 'TX', zip: '78701', notes: 'Door code 4821. Dog is friendly.' } });
const cid = c.customer.id;
await page.goto(BASE + '/app#/customers/' + cid); await page.waitForTimeout(800);
await page.goto(BASE + '/app'); await page.reload(); await page.waitForTimeout(1000); await page.goto(BASE + '/app#/jobs'); await page.waitForTimeout(1000);
await page.click('#nj'); await page.waitForSelector('#chkt');
ok('template buttons shown', (await page.locator('#chkt [data-tpl]').count()) === 3);
await page.click('#chkt [data-tpl="Deep clean"]');
const v1 = await page.inputValue('#chk'); ok('deep clean fills the checklist', /Baseboards/.test(v1) && v1.split('\n').length >= 8, v1);
await page.click('#chkt [data-tpl="Standard clean"]');
ok('templates add to what is there', (await page.inputValue('#chk')).split('\n').length > v1.split('\n').length);
ok('every 2 weeks offered', (await page.locator('#rep option[value="biweekly"]').count()) === 1);
await page.selectOption('#cust', String(cid)); await page.waitForTimeout(500);
await page.fill('#title', 'Biweekly clean'); await page.selectOption('#rep', 'biweekly'); await page.fill('#count', '4');
const d = new Date(Date.now() + 2 * 864e5); d.setHours(9, 0, 0, 0); const pad = n => String(n).padStart(2, '0');
await page.fill('#start', `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}T09:00`);
await page.click('#jf button[type="submit"]'); await page.waitForURL(/#\/jobs\/\d+/); await page.waitForTimeout(1200);
const jid = page.url().match(/jobs\/(\d+)/)[1];
const jd = await api('GET', '/jobs/' + jid);
ok('job repeats weekly with interval 2', jd.job.recurrence && jd.job.recurrence.freq === 'weekly' && jd.job.recurrence.interval === 2, jd.job.recurrence);
ok('visits are 14 days apart', jd.visits.length >= 2 && Math.round((new Date(jd.visits[1].starts_at) - new Date(jd.visits[0].starts_at)) / 864e5) === 14, jd.visits.map(v => v.starts_at));
ok('visit carries the checklist', jd.visits[0].checklist.length >= 8);
const vv = await api('GET', '/visits/' + jd.visits[0].id);
ok('visit API returns entry notes and full address', vv.visit.property_notes === 'Door code 4821. Dog is friendly.' && vv.visit.zip === '78701', vv.visit);
await page.evaluate(id => { location.hash = '#/jobs'; }, 0);
await page.goto(BASE + '/app#/jobs/' + jid); await page.waitForTimeout(800);
await page.locator('[data-visit], [data-vid], .item').first().click().catch(() => {});
await page.waitForTimeout(800);
const modalText = await page.locator('.modal, dialog, [role=dialog]').first().innerText().catch(() => '');
ok('visit screen shows the door code', /Door code 4821/.test(modalText), modalText.slice(0, 120));
ok('no JS errors', errs.length === 0, errs);
console.log(`${pass} passed, ${fail} failed`); await b.close(); srv.close?.(); process.exit(fail ? 1 : 0);
